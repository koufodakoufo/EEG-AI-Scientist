"""Trusted, staged scientific aggregation of bounded candidate evidence.

No candidate code is imported. Labels, targets and participant identities come
only from externally hash-bound private truth. Numeric consistency checks do not
prove that submitted evidence was generated by the claimed fitting/forward pass;
candidate source review and independent replay remain necessary for that claim.
"""
