LAYERS = (6, 12)
GROUP_COLUMNS = tuple(tuple(i for i, column in enumerate(FEATURE_COLUMNS)
                            if column == group or column.startswith(group+':'))
                      for group in FEATURE_IDS)
MAX_ROWS = 4096
MAX_BYTES = 512 * 1024**2
Schema = Mapping[str, tuple[tuple[int | None, ...], str]]


def r2_columns(targets: np.ndarray, predictions: np.ndarray) -> np.ndarray:
    """Reject arithmetic overflow rather than silently omitting a bad score."""
    try:
        with np.errstate(over='raise', invalid='raise', divide='raise'):
            return _raw_r2_columns(targets, predictions)
    except FloatingPointError as error:
        raise ValueError('R2 arithmetic overflow in candidate evidence') from error


def _bounded_npz(path: Path, schema: Schema) -> dict[str, np.ndarray]:
    """Generalize the worker's header-first validator without changing it."""
    path = _path(path)
    if path.stat().st_size > MAX_BYTES:
        raise ValueError('Archive exceeds byte cap')
    initial_hash = digest_file(path)
    with zipfile.ZipFile(path) as archive:
        entries = archive.infolist()
        expected = {name+'.npy' for name in schema}
        if (len(entries) != len(expected) or {item.filename for item in entries} != expected
                or sum(item.file_size for item in entries) > MAX_BYTES):
            raise ValueError('Unexpected scientific array schema or archive size')
        for entry in entries:
            if entry.flag_bits & 1 or entry.compress_type not in {zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED}:
                raise ValueError('Unsupported encrypted/compressed member')
            shape_spec, kinds = schema[entry.filename[:-4]]
            with archive.open(entry) as stream:
                prefix = stream.read(8)
                if prefix[:6] != b'\x93NUMPY' or prefix[6:] not in {b'\x01\x00', b'\x02\x00', b'\x03\x00'}:
                    raise ValueError('Invalid NPY header')
                width = 2 if prefix[6] == 1 else 4
                raw_length = stream.read(width)
                if len(raw_length) != width:
                    raise ValueError('Truncated NPY header')
                length = struct.unpack('<H' if width == 2 else '<I', raw_length)[0]
                if not 0 < length <= 10000:
                    raise ValueError('Oversized NPY header')
                raw_header = stream.read(length)
                if len(raw_header) != length:
                    raise ValueError('Truncated NPY header')
                try:
                    header = ast.literal_eval(raw_header.decode('utf-8' if prefix[6] == 3 else 'latin1'))
                except (ValueError, SyntaxError, UnicodeError, RecursionError) as error:
                    raise ValueError('Malformed NPY header') from error
                if (not isinstance(header, dict) or set(header) != {'descr','shape','fortran_order'}
                        or not isinstance(header['descr'], str) or type(header['fortran_order']) is not bool):
                    raise ValueError('Unsafe NPY descriptor')
                dtype = np.dtype(header['descr'])
                shape = header['shape']
                if (not isinstance(shape, tuple) or len(shape) != len(shape_spec)
                        or any(type(size) is not int or size < 1 or size > MAX_ROWS for size in shape)
                        or any(want is not None and got != want for got,want in zip(shape,shape_spec))
                        or dtype.kind not in kinds or dtype.hasobject or dtype.fields or dtype.subdtype
                        or dtype.itemsize < 1 or dtype.itemsize > (512 if dtype.kind in 'US' else 8)):
                    raise ValueError('Invalid scientific array shape/dtype')
                if 8 + width + length + math.prod(shape)*dtype.itemsize != entry.file_size:
                    raise ValueError('NPY byte length mismatch')
    with np.load(path, allow_pickle=False, max_header_size=10000) as archive:
        arrays = {name:np.array(archive[name], copy=True) for name in schema}
    if digest_file(path) != initial_hash:
        raise ValueError('Archive changed while reading')
    for value in arrays.values():
        if value.dtype.kind in 'fiu' and not np.isfinite(value).all():
            raise ValueError('Nonfinite numeric evidence')
    return arrays


def _truth(binding: FileBinding) -> dict[str, np.ndarray]:
    path = binding.verify()
    arrays = _bounded_npz(path, {'sample_ids':((None,), 'USiu'),
        'subject_ids':((None,), 'USiu'), 'y':((None,), 'iu'), 'features':((None,62), 'fiu')})
    n = len(arrays['sample_ids'])
    if (any(len(value) != n for value in arrays.values()) or n < 4
            or len(set(arrays['sample_ids'].tolist())) != n
            or set(arrays['y'].tolist()) != {0,1}
            or len(np.unique(arrays['subject_ids'])) < 2):
        raise ValueError('Invalid trusted participant/sample/label alignment')
    binding.verify()
    return arrays


def _active(train: Mapping[str, np.ndarray]) -> np.ndarray:
    values = train['features'].astype(float)
    return values.std(0) > np.maximum(np.abs(values.mean(0))*1e-12, 1e-12)


def _mean(values: np.ndarray) -> float:
    finite = values[np.isfinite(values)]
    return float(np.mean(finite)) if len(finite) else float('nan')


def _task_metrics(y: np.ndarray, logits: np.ndarray) -> dict[str, float]:
    predicted = logits >= 0
    accuracy = float(np.mean(predicted == y))
    balanced = _mean(np.asarray([np.mean(predicted[y == c] == c) if np.any(y == c)
                                 else np.nan for c in (0,1)]))
    # Pairwise AUC with half credit for ties; bounded held-out N avoids sklearn.
    positive, negative = logits[y == 1], logits[y == 0]
    auc = float('nan')
    if len(positive) and len(negative):
        ordered = np.sort(negative)
        lower = np.searchsorted(ordered, positive, side='left')
        upper = np.searchsorted(ordered, positive, side='right')
        auc = float(np.mean((lower+upper)/(2*len(negative))))
    return {'accuracy':accuracy, 'balanced_accuracy':balanced, 'auroc':auc}


def _plain(value: Any) -> Any:
    if isinstance(value, np.ndarray):
        return _plain(value.tolist())
    if isinstance(value, np.generic):
        return _plain(value.item())
    if isinstance(value, dict):
        return {str(k):_plain(v) for k,v in value.items()}
    if isinstance(value, (list,tuple)):
        return [_plain(item) for item in value]
    if isinstance(value, float) and not math.isfinite(value):
        return None
    return value


def _write_new(path: Path, value: Any) -> None:
    # A candidate-precreated report must never be mistaken for trusted output.
    _path(path.parent, directory=True)
    with path.open('x', encoding='utf-8') as stream:
        json.dump(_plain(value), stream, sort_keys=True, indent=2, allow_nan=False)
        stream.write('\n')


def _metric_names() -> frozenset[str]:
    names = {'accuracy','balanced_accuracy','auroc','baseline_only','q1_only',
             'q1_groups','q2_interventions','q3_residual_groups','numeric_scope_complete',
             'participants','bootstrap_resamples'}
    for task in ('accuracy','balanced_accuracy','auroc'):
        names.update(f'{task}_ci95_{end}' for end in ('low','high'))
    for layer in LAYERS:
        for group in range(12):
            prefix = f'q1_l{layer}_g{group:02d}_'
            names.update(prefix+key for key in ('r2','negative_r2','r2_minus_negative',
                'active_columns','defined_columns','constant_eval_columns'))
            for key in ('r2_ci95','r2_family_ci','r2_minus_negative_ci95'):
                names.update(prefix+key+'_'+end for end in ('low','high'))
    for selected in range(2):
        prefix = f'q2_s{selected}_'
        names.update(prefix+key for key in ('rank','group','layer','shift_l2_mean',
            'strength_max_abs_error','direction_span_max_error','balanced_accuracy_contrast'))
        for variant in ('learned','control0','control1','control2'):
            names.update(prefix+variant+'_'+key for key in ('accuracy','balanced_accuracy','auroc','balanced_accuracy_delta'))
            names.add(f'q3_s{selected}_{variant}_r2')
        for key in ('balanced_accuracy_contrast_ci95','balanced_accuracy_contrast_family_ci'):
            names.update(prefix+key+'_'+end for end in ('low','high'))
        names.update(f'q3_s{selected}_learned_r2_ci95_{end}' for end in ('low','high'))
    return frozenset(names)


class ScientificAggregator:
    """Callable for SandboxedWorkerEvaluator; stage determined by fixed files.

    Pass ``bindings`` and ``policy_sha256`` to the worker's trusted enrollment.
    Selection bindings are optional, immutable Builder inputs, never candidate
    scalar claims. Q1-only output needs no intervention selection binding.
    """
    released_metrics = _metric_names()

    def __init__(self, truth_by_split: Mapping[str, FileBinding], train_truth: FileBinding, *,
                 selection_by_candidate: Mapping[str, FileBinding] | None = None,
                 bootstrap_resamples: int = 2000) -> None:
        if not truth_by_split or not set(truth_by_split) <= {'validation','test'}:
            raise ValueError('Only explicit validation/test truth bindings are accepted')
        if type(bootstrap_resamples) is not int or not 1 <= bootstrap_resamples <= 10000:
            raise ValueError('Invalid bootstrap resample count')
        self.truth = MappingProxyType(dict(truth_by_split))
        self.train_truth = train_truth
        self.selection = MappingProxyType(dict(selection_by_candidate or {}))
        for digest in self.selection:
            _sha(digest)
        self.bootstrap_resamples = bootstrap_resamples
        self.bindings = (train_truth, *self.truth.values(), *self.selection.values())
        policy = {'schema':'scientific_aggregate_v1', 'bootstrap_resamples':bootstrap_resamples,
                  'seed':20261029, 'layers':LAYERS, 'feature_columns':FEATURE_COLUMNS,
                  'bindings':[{'path':str(item.path.absolute()), 'sha256':item.sha256} for item in self.bindings],
                  'selection_candidates':list(self.selection), 'released_metrics':sorted(self.released_metrics)}
        self.policy_sha256 = hashlib.sha256(canonical_bytes(policy)).hexdigest()

    def _inputs(self, split: str) -> tuple[dict[str,np.ndarray], dict[str,np.ndarray]]:
        if split not in self.truth:
            raise ValueError('No trusted truth for this split')
        train, truth = _truth(self.train_truth), _truth(self.truth[split])
        if (set(train['subject_ids'].tolist()) & set(truth['subject_ids'].tolist())
                or set(train['sample_ids'].tolist()) & set(truth['sample_ids'].tolist())):
            raise ValueError('Training and evaluation participants/samples overlap')
        return train, truth

    def _analysis(self, output: Path, truth: Mapping[str,np.ndarray],
                  train: Mapping[str,np.ndarray]) -> dict[str,np.ndarray]:
        n, t = len(truth['y']), len(train['y'])
        arrays = _bounded_npz(output/'analysis.npz', {
            'sample_ids':((n,), 'USiu'), 'feature_predictions':((n,2,62), 'fiu'),
            'negative_predictions':((n,2,62), 'fiu'), 'negative_train_permutation':((t,), 'iu')})
        if not np.array_equal(arrays['sample_ids'], truth['sample_ids']):
            raise ValueError('Scientific sample IDs must match exact trusted row order')
        permutation = arrays['negative_train_permutation']
        if not np.array_equal(np.sort(permutation), np.arange(t)):
            raise ValueError('Negative target control must be a permutation of training rows')
        subjects = train['subject_ids']
        mapped: list[Any] = []
        for subject in np.unique(subjects):
            rows = np.flatnonzero(subjects == subject)
            destination = np.unique(subjects[permutation[rows]])
            if len(destination) != 1 or destination[0] == subject:
                raise ValueError('Negative control must derange complete participant blocks')
            mapped.append(destination[0])
            # Retaining every within-block position would preserve condition/window alignment.
            if np.array_equal(permutation[rows], np.flatnonzero(subjects == destination[0])):
                raise ValueError('Negative control retained within-participant row alignment')
        if len(set(mapped)) != len(mapped):
            raise ValueError('Negative control does not bijectively map participant blocks')
        changed = np.any(train['features'][permutation] != train['features'], axis=0)
        if not np.all(changed[_active(train)]):
            raise ValueError('An active target column is unchanged by the negative control')
        return arrays

    @staticmethod
    def _selected(truth: Mapping[str,np.ndarray], arrays: Mapping[str,np.ndarray],
                  active: np.ndarray) -> list[dict[str,int]]:
        ranked: list[tuple[float,int,int]] = []
        for layer_index, layer in enumerate(LAYERS):
            values = r2_columns(truth['features'], arrays['feature_predictions'][:,layer_index,:])
            for group, columns in enumerate(GROUP_COLUMNS):
                chosen = np.asarray(columns)[active[list(columns)]]
                score = _mean(values[chosen])
                if np.isfinite(score):
                    ranked.append((-score, group, layer))
        selected: list[dict[str,int]] = []
        for _, group, layer in sorted(ranked):
            if group not in {item['group'] for item in selected}:
                selected.append({'group':group, 'layer':layer})
                if len(selected) == 2:
                    break
        return selected

    def freeze_selection(self, output: Path, spec: EvaluationSpec, destination: Path) -> FileBinding:
        """Builder-only validation evidence freeze, before test enrollment.

        The caller obtains this output only from a succeeded trusted worker and
        enrolls the returned FileBinding in the subsequent test evaluator.
        """
        if spec.split != 'validation':
            raise ValueError('Selections may only be frozen from validation')
        _sha(spec.candidate_digest)
        train, truth = self._inputs('validation')
        arrays = self._analysis(output, truth, train)
        selected = self._selected(truth, arrays, _active(train))
        if len(selected) != 2:
            raise ValueError('Two estimable distinct feature groups are required')
        document = {'schema':'scientific_selection_v1', 'split':'validation',
                    'candidate_digest':spec.candidate_digest, 'selected':selected,
                    'analysis_sha256':digest_file(output/'analysis.npz'),
                    'validation_truth_sha256':self.truth['validation'].sha256,
                    'train_truth_sha256':self.train_truth.sha256}
        _write_new(destination, document)
        return FileBinding(destination, digest_file(destination))

    def _selection(self, spec: EvaluationSpec, output: Path,
                   train: Mapping[str,np.ndarray], arrays: Mapping[str,np.ndarray],
                   truth: Mapping[str,np.ndarray]) -> list[dict[str,int]]:
        if spec.candidate_digest in self.selection:
            binding = self.selection[spec.candidate_digest]
            path = binding.verify()
            if path.stat().st_size > 16384:
                raise ValueError('Oversized trusted selection')
            document = json.loads(path.read_text(encoding='utf-8'))
            if (document.get('schema') != 'scientific_selection_v1' or document.get('split') != 'validation'
                    or document.get('candidate_digest') != spec.candidate_digest
                    or 'validation' not in self.truth
                    or document.get('validation_truth_sha256') != self.truth['validation'].sha256
                    or document.get('train_truth_sha256') != self.train_truth.sha256):
                raise ValueError('Trusted selection binding mismatch')
            _sha(document.get('analysis_sha256', ''))
            selected = document.get('selected')
            binding.verify()
            if spec.split == 'validation':
                if (document['analysis_sha256'] != digest_file(output/'analysis.npz')
                        or selected != self._selected(truth, arrays, _active(train))):
                    raise ValueError('Validation evidence differs from frozen selection')
        elif spec.split == 'validation':
            selected = self._selected(truth, arrays, _active(train))
        else:
            # A frozen candidate may carry raw validation predictions, never
            # claimed selected indices/scores. The digest covers these bytes.
            candidate = getattr(spec, 'candidate_dir', None)
            if candidate is None or candidate_digest(candidate) != spec.candidate_digest or 'validation' not in self.truth:
                raise ValueError('Test interventions require frozen validation selection evidence')
            validation = _truth(self.truth['validation'])
            frozen = _bounded_npz(candidate/'validation_selection.npz', {
                'sample_ids':((len(validation['y']),), 'USiu'),
                'feature_predictions':((len(validation['y']),2,62), 'fiu')})
            if not np.array_equal(frozen['sample_ids'], validation['sample_ids']):
                raise ValueError('Frozen validation rows mismatch')
            selected = self._selected(validation, frozen, _active(train))
            if candidate_digest(candidate) != spec.candidate_digest:
                raise ValueError('Candidate changed while reading validation evidence')
        if (not isinstance(selected, list) or len(selected) != 2
                or any(not isinstance(item, dict) or set(item) != {'group','layer'}
                       or type(item['group']) is not int or item['group'] not in range(12)
                       or item['layer'] not in LAYERS for item in selected)
                or selected[0]['group'] == selected[1]['group']):
            raise ValueError('Invalid fixed two-group selection')
        return selected

    def __call__(self, output: Path, spec: EvaluationSpec) -> dict[str,Any]:
        output = _path(output, directory=True)
        train, truth = self._inputs(spec.split)
        results_path = _path(output/'results.npz')
        # Reuse the frozen worker's existing header-first classification checks.
        baseline = validate_prediction_npz(results_path, self.truth[spec.split].verify())
        if set(baseline) != {'logits','sample_ids','trusted_y'}:
            raise ValueError('Use analysis.npz for the fixed two-layer feature schema')
        y, logits = truth['y'], baseline['logits']
        metrics = _task_metrics(y, logits)
        metrics.update(baseline_only=1., q1_only=0., q1_groups=0., q2_interventions=0.,
                       q3_residual_groups=0., numeric_scope_complete=0.,
                       participants=float(len(np.unique(truth['subject_ids']))),
                       bootstrap_resamples=float(self.bootstrap_resamples))
        samples = cluster_bootstrap_indices(truth['subject_ids'], resamples=self.bootstrap_resamples, seed=20261029)
        for name in ('accuracy','balanced_accuracy','auroc'):
            self._ci(metrics, name+'_ci95', np.asarray([_task_metrics(y[rows],logits[rows])[name] for rows in samples]))
        report: dict[str,Any] = {'schema':'trusted_scientific_analysis_v1', 'split':spec.split,
            'candidate_digest':spec.candidate_digest, 'scope':'baseline', 'q1':[], 'q2':[],
            'uncertainty':{'unit':'participant', 'resamples':self.bootstrap_resamples, 'seed':20261029,
                           'intervals':'95% marginal, not simultaneous; adjusted bootstrap quantiles are approximate',
                           'q1_family_size':24, 'q2_family_size':2},
            'limitations':['Numeric evidence consistency is checked; fitting, randomization seed, forward-pass and residual-refit provenance require source review and independent replay.',
                          'Recoverability does not establish task reliance; representation effects do not establish physiological causation.',
                          'Small held-out participant count limits bootstrap and generalization. Null and negative results are retained.']}
        artifacts = [results_path]
        analysis_path, interventions_path = output/'analysis.npz', output/'interventions.npz'
        candidate = getattr(spec, 'candidate_dir', None)
        if (spec.split == 'validation' and candidate is not None
                and (candidate/'validation_selection.npz').exists() and not analysis_path.exists()):
            raise ValueError('Frozen validation selection requires actual validation analysis')
        if interventions_path.exists() and not analysis_path.exists():
            raise ValueError('Interventions require Q1 evidence')
        if analysis_path.exists():
            arrays = self._analysis(output, truth, train)
            if spec.split == 'validation' and candidate is not None and (candidate/'validation_selection.npz').exists():
                if candidate_digest(candidate) != spec.candidate_digest:
                    raise ValueError('Candidate selection bytes are not frozen')
                frozen = _bounded_npz(candidate/'validation_selection.npz', {
                    'sample_ids':((len(y),), 'USiu'), 'feature_predictions':((len(y),2,62), 'fiu')})
                if (not np.array_equal(frozen['sample_ids'], arrays['sample_ids'])
                        or not np.array_equal(frozen['feature_predictions'], arrays['feature_predictions'])
                        or candidate_digest(candidate) != spec.candidate_digest):
                    raise ValueError('Frozen validation predictions differ from actual validation evidence')
            metrics['baseline_only'], metrics['q1_only'] = 0., 1.
            report['scope'] = 'Q1 only'
            active = _active(train)
            self._q1(metrics, report, truth, arrays, active, samples)
            artifacts.append(analysis_path)
            if interventions_path.exists():
                selected = self._selection(spec, output, train, arrays, truth)
                self._q2(metrics, report, truth, active, selected, logits, samples, interventions_path)
                metrics['q1_only'] = 0.
                report['scope'] = 'Q1-Q3'
                artifacts.append(interventions_path)
            metrics['numeric_scope_complete'] = float(metrics['q1_groups'] == 24 and metrics['q2_interventions'] == 2
                                                    and metrics['q3_residual_groups'] == 2)
        # Recheck externally enrolled truth after calculation, before publication.
        self.train_truth.verify()
        self.truth[spec.split].verify()
        metrics = {key:float(value) for key,value in metrics.items() if np.isfinite(value)}
        if not set(metrics) <= self.released_metrics:
            raise ValueError('Undeclared metric')
        report['metrics'] = metrics
        report_path = output/'trusted_analysis.json'
        _write_new(report_path, report)
        artifacts.append(report_path)
        return {'metrics':metrics, 'artifacts':[{'path':path.name, 'sha256':digest_file(path)} for path in artifacts]}

    @staticmethod
    def _ci(metrics: dict[str,float], prefix: str, values: np.ndarray, confidence: float = .95) -> None:
        for end, value in zip(('low','high'), interval(values, confidence=confidence)):
            if value is not None:
                metrics[prefix+'_'+end] = value

    def _q1(self, metrics: dict[str,float], report: dict[str,Any], truth: Mapping[str,np.ndarray],
            arrays: Mapping[str,np.ndarray], active: np.ndarray, samples: list[np.ndarray]) -> None:
        targets = truth['features']
        for layer_index, layer in enumerate(LAYERS):
            prediction, negative = arrays['feature_predictions'][:,layer_index,:], arrays['negative_predictions'][:,layer_index,:]
            values, control = r2_columns(targets,prediction), r2_columns(targets,negative)
            boots = np.asarray([r2_columns(targets[rows],prediction[rows]) for rows in samples])
            negative_boots = np.asarray([r2_columns(targets[rows],negative[rows]) for rows in samples])
            for group, columns in enumerate(GROUP_COLUMNS):
                selected = np.asarray(columns)[active[list(columns)]]
                raw, null = values[selected], control[selected]
                score, null_score = _mean(raw), _mean(null)
                prefix = f'q1_l{layer}_g{group:02d}_'
                metrics[prefix+'active_columns'] = float(len(selected))
                metrics[prefix+'defined_columns'] = float(np.isfinite(raw).sum())
                metrics[prefix+'constant_eval_columns'] = float(np.sum(~np.isfinite(values[list(columns)])))
                metrics.update({prefix+'r2':score, prefix+'negative_r2':null_score, prefix+'r2_minus_negative':score-null_score})
                if np.isfinite(score):
                    metrics['q1_groups'] += 1
                bootstrap = np.asarray([_mean(row[selected]) for row in boots])
                control_bootstrap = np.asarray([_mean(row[selected]) for row in negative_boots])
                self._ci(metrics, prefix+'r2_ci95', bootstrap)
                self._ci(metrics, prefix+'r2_family_ci', bootstrap, 1-.05/24)
                self._ci(metrics, prefix+'r2_minus_negative_ci95', bootstrap-control_bootstrap)
                report['q1'].append({'group':group, 'feature':FEATURE_IDS[group], 'layer':layer,
                    'columns':list(columns), 'column_r2':values[list(columns)],
                    'negative_column_r2':control[list(columns)], 'active_train_columns':active[list(columns)],
                    'r2':score, 'negative_r2':null_score})

    def _q2(self, metrics: dict[str,float], report: dict[str,Any], truth: Mapping[str,np.ndarray],
            active: np.ndarray, selected: list[dict[str,int]], original_logits: np.ndarray,
            samples: list[np.ndarray], path: Path) -> None:
        # Finite submitted arrays can still overflow when shifts are squared.
        # Inf/NaN comparisons must never certify norm matching or span membership.
        try:
            with np.errstate(over='raise', invalid='raise', divide='raise'):
                self._q2_evidence(metrics, report, truth, active, selected,
                                  original_logits, samples, path)
        except FloatingPointError as error:
            raise ValueError('Nonfinite derived intervention evidence') from error

    def _q2_evidence(self, metrics: dict[str,float], report: dict[str,Any], truth: Mapping[str,np.ndarray],
                     active: np.ndarray, selected: list[dict[str,int]], original_logits: np.ndarray,
                     samples: list[np.ndarray], path: Path) -> None:
        n = len(truth['y'])
        evidence = _bounded_npz(path, {'sample_ids':((n,), 'USiu'),
            'selected_groups':((2,), 'iu'), 'selected_layers':((2,), 'iu'),
            'directions':((2,200,6), 'fiu'), 'control_directions':((2,3,200,6), 'fiu'),
            'original_pooled':((2,n,200), 'fiu'), 'altered_pooled':((2,4,n,200), 'fiu'),
            'altered_logits':((2,4,n), 'fiu'), 'residual_predictions':((2,4,n,62), 'fiu')})
        if (not np.array_equal(evidence['sample_ids'], truth['sample_ids'])
                or evidence['selected_groups'].tolist() != [item['group'] for item in selected]
                or evidence['selected_layers'].tolist() != [item['layer'] for item in selected]):
            raise ValueError('Intervention rows or validation-selected feature/layer mismatch')
        y, targets = truth['y'], truth['features']
        original_ba = _task_metrics(y,original_logits)['balanced_accuracy']
        for index, choice in enumerate(selected):
            columns = np.asarray(GROUP_COLUMNS[choice['group']])
            columns = columns[active[columns]]
            directions = evidence['directions'][index]
            if np.any(directions[:,len(columns):] != 0):
                raise ValueError('Unused direction columns must be zero padding')
            learned = subspace(directions)
            rank = learned.shape[1]
            if not 0 < rank <= len(columns):
                raise ValueError('A positive actual rank is required')
            shifts = evidence['original_pooled'][index][None,:,:]-evidence['altered_pooled'][index]
            norms = np.linalg.norm(shifts, axis=2)
            if not np.any(norms[0] > 1e-12):
                raise ValueError('Intervention has zero strength in every window')
            if not np.allclose(norms[1:], norms[0][None,:], rtol=1e-6, atol=1e-8):
                raise ValueError('Control strength must match each individual window')
            bases = [learned]
            for control in evidence['control_directions'][index]:
                basis = subspace(control)
                if basis.shape[1] != rank:
                    raise ValueError('Controls must match actual numerical rank')
                if any(np.allclose(basis@basis.T, prior@prior.T, rtol=1e-6, atol=1e-8) for prior in bases):
                    raise ValueError('Controls must have distinct subspaces')
                bases.append(basis)
            errors: list[float] = []
            for shift, basis in zip(shifts,bases):
                residual = shift-(shift@basis)@basis.T
                error = float(np.max(np.linalg.norm(residual,axis=1)))
                if np.any(np.linalg.norm(residual,axis=1) > 1e-8+1e-6*np.linalg.norm(shift,axis=1)):
                    raise ValueError('Recorded shifts do not lie in the recorded direction spans')
                errors.append(error)
            prefix = f'q2_s{index}_'
            metrics.update({prefix+'rank':float(rank), prefix+'group':float(choice['group']),
                            prefix+'layer':float(choice['layer']), prefix+'shift_l2_mean':float(norms[0].mean()),
                            prefix+'strength_max_abs_error':float(np.max(np.abs(norms[1:]-norms[0]))),
                            prefix+'direction_span_max_error':max(errors)})
            altered_logits = evidence['altered_logits'][index]
            scores = [_task_metrics(y,logits) for logits in altered_logits]
            residual_scores: list[float] = []
            for variant_index, name in enumerate(('learned','control0','control1','control2')):
                metrics.update({prefix+name+'_'+key:value for key,value in scores[variant_index].items()})
                metrics[prefix+name+'_balanced_accuracy_delta'] = scores[variant_index]['balanced_accuracy']-original_ba
                predictions = evidence['residual_predictions'][index,variant_index]
                score = _mean(r2_columns(targets[:,columns],predictions[:,columns]))
                metrics[f'q3_s{index}_{name}_r2'] = score
                residual_scores.append(score)
                if variant_index == 0:
                    self._ci(metrics, f'q3_s{index}_learned_r2_ci95', np.asarray([
                        _mean(r2_columns(targets[rows][:,columns], predictions[rows][:,columns])) for rows in samples]))
            contrast = scores[0]['balanced_accuracy']-float(np.mean([item['balanced_accuracy'] for item in scores[1:]]))
            metrics[prefix+'balanced_accuracy_contrast'] = contrast
            bootstrap = np.asarray([_task_metrics(y[rows],altered_logits[0,rows])['balanced_accuracy']
                - np.mean([_task_metrics(y[rows],values[rows])['balanced_accuracy'] for values in altered_logits[1:]]) for rows in samples])
            self._ci(metrics, prefix+'balanced_accuracy_contrast_ci95', bootstrap)
            self._ci(metrics, prefix+'balanced_accuracy_contrast_family_ci', bootstrap, .975)
            metrics['q2_interventions'] += 1
            metrics['q3_residual_groups'] += float(np.isfinite(residual_scores).all())
            report['q2'].append({**choice, 'rank':rank, 'balanced_accuracy_contrast':contrast,
                'residual_r2':residual_scores, 'evidence_checks':['actual numerical ranks','distinct control spans',
                    'per-window shift norm matching','shifts in declared spans','validation-only feature/layer choice'],
                'unverified_execution_claims':['training-only direction fitting','three declared random seeds',
                    'same activation shift at every token','remaining frozen layers/head replay','residual train refit']})
